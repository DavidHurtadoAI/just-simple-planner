import { readFile, stat } from 'node:fs/promises';
import assert from 'node:assert/strict';
const manifest = JSON.parse(await readFile(new URL('../manifest.json', import.meta.url)));
const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url)));
const versions = JSON.parse(await readFile(new URL('../versions.json', import.meta.url)));
assert.equal(manifest.id, pkg.name);
assert.match(manifest.id, /^[a-z0-9]+(?:-[a-z0-9]+)*$/);
assert.ok(!manifest.id.includes('obsidian'));
assert.match(manifest.version, /^\d+\.\d+\.\d+$/);
assert.match(manifest.minAppVersion, /^\d+\.\d+\.\d+$/);
assert.ok(typeof manifest.name === 'string' && manifest.name.trim());
assert.ok(typeof manifest.author === 'string' && manifest.author.trim());
assert.ok(typeof manifest.description === 'string' && manifest.description.length > 0 && manifest.description.length <= 250);
assert.ok(manifest.description.endsWith('.'));
assert.equal(typeof manifest.isDesktopOnly, 'boolean');
assert.equal(manifest.version, pkg.version);
assert.equal(versions[pkg.version], manifest.minAppVersion);
assert.equal(Object.keys(pkg.dependencies ?? {}).length, 0);
for (const name of ['main.js', 'styles.css', 'LICENSE', 'README.md']) assert.ok((await stat(new URL(`../${name}`, import.meta.url))).size > 0);
const code = await readFile(new URL('../main.js', import.meta.url), 'utf8');
assert.ok(!/\b(?:fetch|XMLHttpRequest|WebSocket)\s*\(/.test(code), 'Unexpected network primitive');
const imports = [...code.matchAll(/\brequire\(["']([^"']+)["']\)/g)].map(match => match[1]);
assert.deepEqual([...new Set(imports)], ['obsidian'], 'Only Obsidian may remain external to the bundle');
assert.ok(!/\b(?:eval|Function)\s*\(/.test(code), 'Unexpected dynamic code execution');
console.log(`Package OK: ${manifest.name} ${manifest.version}; no runtime dependencies; ${(Buffer.byteLength(code) / 1024).toFixed(1)} KiB JS.`);
